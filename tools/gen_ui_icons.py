def render(rows):
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = im.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row.ljust(16, ".")[:16]):
            if ch in PAL:
                px[x, y] = PAL[ch]
    out = im.copy()
    o = out.load()
    for y in range(16):
        for x in range(16):
            if px[x, y][3]:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < 16 and 0 <= ny < 16 and px[nx, ny][3]:
                    o[x, y] = OUTLINE
                    break
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, rows in ICONS.items():
        render(rows).save(os.path.join(OUT, name + ".png"))
    print("Đã vẽ %d biểu tượng → %s" % (len(ICONS), OUT))


if __name__ == "__main__":
    main()
